// Smoke test: renders the real dashboard webview script against a mock state with a
// minimal DOM stub and asserts the usage distribution (Claude + Codex shares) shows up.
const { test, before } = require('node:test');
const assert = require('node:assert/strict');
const Module = require('node:module');

const stubVscode = {
  Disposable: class { constructor(fn) { this.fn = fn; } dispose() { this.fn?.(); } },
  window: {
    createWebviewPanel: () => { throw new Error('not used'); },
    registerWebviewViewProvider: () => ({ dispose() {} }),
  },
  workspace: { onDidChangeConfiguration: () => ({ dispose() {} }) },
  Uri: { joinPath: () => ({}) },
  StatusBarAlignment: { Right: 2 }, ViewColumn: { Active: 1 },
};
const originalLoad = Module._load;
Module._load = function (request, ...rest) {
  return request === 'vscode' ? stubVscode : originalLoad.call(this, request, ...rest);
};

const { UsageViewProvider } = require('../out/dashboard.js');

function metrics(spend, tokens, requests) {
  return { spend, prompt_tokens: tokens * 0.75, completion_tokens: tokens * 0.25, total_tokens: tokens, api_requests: requests, successful_requests: requests, failed_requests: 0 };
}

const today = new Date().toISOString().slice(0, 10);
const day1 = new Date(Date.now() - 86400000).toISOString().slice(0, 10);

// Mirrors state produced by UsageController.aggregate for a Claude + Codex proxy.
const state = {
  configured: true, loading: false, host: 'litellm.example.com', accountLabel: 'work', accounts: [],
  range: 7, scope: 'user', error: undefined, userInfo: undefined, keyInfo: { key_alias: 'work', spend: 10, max_budget: 100 },
  models: ['claude-sonnet-4-5-20250929', 'gpt-5.1-codex'],
  days: [{ date: day1, metrics: metrics(5, 7000, 10) }, { date: today, metrics: metrics(5, 9000, 10) }],
  modelUsage: [
    { name: 'claude-sonnet-4-5-20250929', metrics: metrics(4, 5000, 8) },
    { name: 'gpt-5.1-codex', metrics: metrics(3.75, 9000, 10) },
    { name: 'codex-mini-latest', metrics: metrics(1.25, 1000, 1) },
    { name: 'claude-haiku-4-5-20251001-v1:0', metrics: metrics(1, 1000, 1) },
  ],
  modelGroups: [
    { name: 'Codex', metrics: metrics(5, 10000, 11), spendPct: 50, tokensPct: 62.5, requestsPct: 55 },
    { name: 'Claude Sonnet 4.5', metrics: metrics(4, 5000, 8), spendPct: 40, tokensPct: 31.25, requestsPct: 40 },
    { name: 'Claude Haiku 4.5', metrics: metrics(1, 1000, 1), spendPct: 10, tokensPct: 6.25, requestsPct: 5 },
  ],
  totals: metrics(10, 16000, 20), today: metrics(5, 9000, 10), activityUnsupported: false,
  lastUpdated: new Date(2026, 10, 5, 14, 7).toISOString(),
  dateFormat: { date: 'dd.MM.yyyy', time: 'HH:mm' },
};

let root, messageHandler;

before(() => {
  // Capture the webview HTML generated by the provider, then run its inline script with a DOM stub.
  let html = '';
  const provider = new UsageViewProvider({ state, refresh: async () => {} });
  provider.resolveWebviewView({
    webview: { options: {}, set html(v) { html = v; }, onDidReceiveMessage: () => ({ dispose() {} }) },
    onDidDispose: () => {},
  });
  const script = /<script nonce="[^"]*">([\s\S]*?)<\/script>/.exec(html)[1];

  root = { innerHTML: '', classList: { remove: () => {}, add: () => {} } };
  const listeners = {};
  global.acquireVsCodeApi = () => ({ postMessage: () => {} });
  global.window = { addEventListener: (ev, fn) => { listeners[ev] = fn; } };
  global.document = {
    body: { classList: { contains: () => false } },
    addEventListener: () => {},
    getElementById: () => root,
  };
  global.getComputedStyle = () => ({ getPropertyValue: () => '' });
  new Function(script)();
  messageHandler = listeners.message;
  assert.ok(messageHandler, 'webview registers a message listener');
});

test('renders the stacked usage share bar with Claude and Codex slices', () => {
  messageHandler({ data: { type: 'state', state } });
  const out = root.innerHTML;
  assert.match(out, /Usage share/);
  assert.match(out, /Codex/);
  assert.match(out, /Claude Sonnet 4\.5/);
  assert.match(out, /Claude Haiku 4\.5/);
  assert.match(out, /50\.0%/, 'Codex spend share');
  assert.match(out, /40\.0%/, 'Claude Sonnet spend share');
  assert.match(out, /data-action="dist" data-value="tokens"/, 'metric switch buttons');
  assert.match(out, /<td class="pct">40\.0%/, 'per-model share column');
});

test('models table carries the full Claude + Codex aliases with token shares', () => {
  messageHandler({ data: { type: 'state', state } });
  const out = root.innerHTML;
  for (const alias of ['claude-sonnet-4-5-20250929', 'gpt-5.1-codex', 'codex-mini-latest']) {
    assert.ok(out.includes(alias), `table lists ${alias}`);
  }
  assert.match(out, /<th>Share<\/th>/);
  assert.match(out, /<th>Tok\.%<\/th>/);
});

test('dates follow the OS regional format (day first, 24-hour clock)', () => {
  messageHandler({ data: { type: 'state', state } });
  const out = root.innerHTML;
  assert.match(out, /Last updated: 05\.11\.2026 14:07/);
  const [y, m, d] = today.split('-');
  assert.ok(out.includes('>' + d + '.' + m + '</text>'), 'chart label is day.month');
  assert.ok(out.includes('<title>' + d + '.' + m + '.' + y + ':'), 'chart tooltip uses the full OS date');
  assert.doesNotMatch(out, /\d (AM|PM)\b/);
});
